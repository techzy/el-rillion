// Validates content/ and writes supabase/seed.sql (a full content reset).
// Usage: npm run seed
import { writeFileSync } from "node:fs";
import { packs } from "../content/index.mjs";

const TIERS = [10, 15, 30, 60, 85, 100];
const GREEK = [["Ω", "omega"], ["ω", "omega"], ["μ", "u"], ["µ", "u"], ["σ", "sigma"], ["Σ", "sigma"],
  ["δ", "delta"], ["Δ", "delta"], ["α", "alpha"], ["β", "beta"], ["π", "pi"], ["²", "2"], ["θ", "theta"], ["+", "plus"]];
// Mirror of public.el_norm (validation only; the database computes keys itself).
export function norm(t) {
  let s = t;
  for (const [a, b] of GREEK) s = s.split(a).join(b);
  s = s.normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/[øØ]/g, "o").toLowerCase().replace(/[^a-z0-9]/g, "");
  if (s.length > 3 && s.endsWith("s")) s = s.slice(0, -1);
  return s;
}

const errors = [];
const ids = new Set();
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const out = ["-- Generated by scripts/build-seed.mjs. Replaces ALL content (and, via cascade, all play history).", "begin;",
  "delete from public.plays; delete from public.answer_keys; delete from public.answers; delete from public.prompts; delete from public.packs;"];
let nPrompts = 0, nAnswers = 0;

packs.forEach((pack, pi) => {
  out.push(`insert into public.packs (id, name, description, sort) values (${q(pack.id)}, ${q(pack.name)}, ${q(pack.description)}, ${pi});`);
  if (pack.chapters.length !== 2) errors.push(`${pack.id}: needs 2 chapters`);
  pack.chapters.forEach((ch, ci) => {
    if (ch.length !== 7) errors.push(`${pack.id} chapter ${ci + 1}: has ${ch.length} prompts, needs 7`);
    ch.forEach((pr, si) => {
      if (!pr || !pr.id) { errors.push(`${pack.id} ch${ci + 1}#${si}: missing prompt`); return; }
      if (ids.has(pr.id)) errors.push(`duplicate prompt id ${pr.id}`);
      ids.add(pr.id);
      const seen = new Map(); let tops = 0, count = 0;
      for (const line of pr.body.split("\n").map((l) => l.trim()).filter(Boolean)) {
        const m = line.match(/^(\d+)\s+(.+)$/);
        if (!m) { errors.push(`${pr.id}: bad line "${line}"`); continue; }
        const tier = Number(m[1]);
        if (!TIERS.includes(tier)) errors.push(`${pr.id}: bad tier in "${line}"`);
        if (tier === 100) tops++;
        if (m[2].includes("$b$")) errors.push(`${pr.id}: "$b$" not allowed`);
        const names = m[2].split("|").map((s) => s.trim()).filter(Boolean);
        for (const k of new Set(names.map(norm))) {
          if (!k) errors.push(`${pr.id}: empty key in "${line}"`);
          else if (seen.has(k)) errors.push(`${pr.id}: "${k}" used by both "${seen.get(k)}" and "${names[0]}"`);
          else seen.set(k, names[0]);
        }
        count++;
      }
      if (tops !== 1) errors.push(`${pr.id}: needs exactly one 100 (has ${tops})`);
      nPrompts++; nAnswers += count;
      out.push(`select public.el_seed_prompt(${q(pack.id)}, ${ci + 1}, ${si}, ${q(pr.id)}, ${q(pr.title)}, $b$\n${pr.body}\n$b$);`);
    });
  });
});
out.push("commit;");

if (errors.length) { console.error(errors.join("\n")); process.exit(1); }
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), out.join("\n") + "\n");
console.log(`OK: ${packs.length} packs, ${nPrompts} prompts, ${nAnswers} answers -> supabase/seed.sql`);
