// Validates content/packs.mjs and writes supabase/seed.sql.
// Usage: npm run seed
import { writeFileSync } from "node:fs";
import { packs } from "../content/packs.mjs";

// Mirror of public.el_norm in SQL (used only for validation here; the DB computes keys itself).
const GREEK = [["Ω", "omega"], ["ω", "omega"], ["μ", "u"], ["µ", "u"], ["σ", "sigma"], ["Σ", "sigma"],
  ["δ", "delta"], ["Δ", "delta"], ["α", "alpha"], ["β", "beta"], ["π", "pi"], ["²", "2"]];
export function norm(t) {
  let s = t;
  for (const [a, b] of GREEK) s = s.split(a).join(b);
  s = s.normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/ø/gi, "o").toLowerCase().replace(/[^a-z0-9]/g, "");
  if (s.length > 3 && s.endsWith("s")) s = s.slice(0, -1);
  return s;
}

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const errors = [];
const out = [];
out.push("-- Generated by scripts/build-seed.mjs. Do not edit by hand.");
out.push("begin;");
out.push("delete from public.answer_keys; delete from public.answers; delete from public.prompts; delete from public.packs;");

// Interleave packs for the daily rotation: pack1 prompt1, pack2 prompt1, ...
const dailyOrder = new Map();
let k = 0;
const maxLen = Math.max(...packs.map((p) => p.prompts.length));
for (let i = 0; i < maxLen; i++) for (const p of packs) if (p.prompts[i]) dailyOrder.set(p.prompts[i].id, k++);

let totalAnswers = 0;
packs.forEach((pack, pi) => {
  out.push(`insert into public.packs (id, name, description, sort) values (${q(pack.id)}, ${q(pack.name)}, ${q(pack.description)}, ${pi});`);
  pack.prompts.forEach((pr, si) => {
    const parsed = pr.answers.map((line) => {
      const [name, rarity, aliases = ""] = line.split("|");
      return { name: name.trim(), rarity: Number(rarity), aliases: aliases.split(";").map((a) => a.trim()).filter(Boolean) };
    });
    const max = Math.max(...parsed.map((a) => a.rarity));
    const tops = parsed.filter((a) => a.rarity === max);
    if (tops.length !== 1) errors.push(`${pr.id}: ${tops.length} answers tie for top rarity ${max}`);
    const seen = new Map();
    for (const a of parsed) {
      if (!Number.isInteger(a.rarity) || a.rarity < 1 || a.rarity > 100) errors.push(`${pr.id}: bad rarity for ${a.name}`);
      const keys = new Set([a.name, ...a.aliases].map(norm));
      for (const key of keys) {
        if (!key) errors.push(`${pr.id}: empty key from ${a.name}`);
        else if (seen.has(key)) errors.push(`${pr.id}: key "${key}" used by both "${seen.get(key)}" and "${a.name}"`);
        else seen.set(key, a.name);
      }
    }
    totalAnswers += parsed.length;
    out.push(`select public.el_seed_prompt(${q(pack.id)}, ${q(pr.id)}, ${q(pr.title)}, ${q(pr.blurb)}, ${si}, ${dailyOrder.get(pr.id)}, array[\n${pr.answers.map(q).join(",\n")}]);`);
  });
});
out.push("commit;");

if (errors.length) {
  console.error(errors.join("\n"));
  process.exit(1);
}
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), out.join("\n") + "\n");
console.log(`OK: ${packs.length} packs, ${packs.reduce((n, p) => n + p.prompts.length, 0)} prompts, ${totalAnswers} answers -> supabase/seed.sql`);
